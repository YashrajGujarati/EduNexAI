                </div>
                <button onclick="window.print()" class="btn btn-outline-secondary btn-sm"><i class="fas fa-print me-1"></i> Print Transcript</button>
            </div>

            <div class="card-body p-4">
                <div class="row align-items-center mb-4">
                    <div class="col-md-8">
                        <h5 class="fw-bold text-dark mb-1">Cumulative Mark Overview</h5>
                        <p class="text-muted small mb-0">Class: <strong><?php echo htmlspecialchars($student['class'] ?? 'N/A'); ?></strong> | Roll No: <strong><?php echo htmlspecialchars($student['roll_number'] ?? 'N/A'); ?></strong></p>
                    </div>
                    <div class="col-md-4 text-md-end mt-3 mt-md-0">
                        <span class="text-muted small d-block mb-1">Final Result Standing</span>
                        <span class="badge-status <?php echo ($final_status === 'PASSED') ? 'badge-pass' : 'badge-fail'; ?> fs-6 px-4 py-2">
                            <i class="fas fa-award me-1"></i> <?php echo $final_status; ?> (<?php echo $percentage; ?>%)
                        </span>
                    </div>
                </div>

                <div class="table-responsive">
                    <table class="table table-hover align-middle mb-0">
                        <thead class="table-light">
                            <tr>
                                <th class="ps-4">Course Subject</th>
                                <th>Internal Score (40)</th>
                                <th>External Score (60)</th>
                                <th>Total Score (100)</th>
                                <th class="text-end pe-4">Subject Standing</th>
                            </tr>
                        </thead>
                        <tbody>
                        <?php if (count($results) > 0): ?>
                            <?php foreach ($results as $row): 
                                $t = (int)$row['total_marks'];
                                $badge_class = ($t >= 40) ? 'badge-pass' : 'badge-fail';
                                $sub_status = ($t >= 40) ? 'Pass' : 'Fail';
                            ?>
                            <tr>
                                <td class="ps-4 fw-semibold text-dark"><i class="fas fa-book-bookmark text-primary me-2"></i><?php echo htmlspecialchars($row['subject_name']); ?></td>
                                <td><?php echo (int)$row['internal_marks']; ?> / 40</td>
                                <td><?php echo (int)$row['external_marks']; ?> / 60</td>
                                <td class="fw-bold text-dark fs-6"><?php echo $t; ?> / 100</td>
                                <td class="text-end pe-4">
                                    <span class="badge-status <?php echo $badge_class; ?>"><?php echo $sub_status; ?></span>
                                </td>
                            </tr>
                            <?php endforeach; ?>
                            <tr class="table-light">
                                <td class="ps-4 fw-bold text-dark fs-6" colspan="3">Grand Total Marks Obtained:</td>
                                <td class="fw-bold text-primary fs-5" colspan="2"><?php echo $total_obtained; ?> / <?php echo $total_max; ?> (<?php echo $percentage; ?>%)</td>
                            </tr>
                        <?php else: ?>
                            <tr>
                                <td colspan="5">
                                    <div class="empty-state">

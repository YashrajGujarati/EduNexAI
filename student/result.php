<?php
session_start();

if (!isset($_SESSION['user_id']) || $_SESSION['role'] !== "student") {
    header("Location: ../login.php");
    exit();
}

require_once(__DIR__ . '/../config/db.php');

$user_id = $_SESSION['user_id'];
$getStudent = db_query($conn, "SELECT student_id, class, roll_number FROM students WHERE user_id='$user_id'");
$student = db_fetch_assoc($getStudent);
$student_id = $student['student_id'] ?? 0;

$query = db_query($conn, "
    SELECT
        subjects.subject_name,
        marks.internal_marks,
        marks.external_marks,
        (COALESCE(marks.internal_marks,0) + COALESCE(marks.external_marks,0)) AS total_marks
    FROM marks
    INNER JOIN subjects ON marks.subject_id = subjects.subject_id
    WHERE marks.student_id='$student_id'
");

$results = [];
$total_obtained = 0;
$total_max = 0;
$has_failed = false;

if ($query) {
    while ($row = db_fetch_assoc($query)) {
        $results[] = $row;
        $t = (int)$row['total_marks'];
        $total_obtained += $t;
        $total_max += 100;
        if ($t < 40) $has_failed = true;
    }
}

$percentage = ($total_max > 0) ? round(($total_obtained / $total_max) * 100, 1) : 0;
$final_status = ($total_max > 0 && !$has_failed && $percentage >= 40) ? 'PASSED' : 'NEEDS REVIEW';

$page_title = "My Academic Result";
?>

